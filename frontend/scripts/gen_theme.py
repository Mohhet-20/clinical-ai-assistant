"""Generate src/theme.css: Tailwind colour scales as CSS variables (RGB triplets), redefined for dark mode.

    python scripts/gen_theme.py src/theme.css
"""
import sys

STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900]
LIGHT = {
    "slate": "f8fafc f1f5f9 e2e8f0 cbd5e1 566579 4b596c 475569 334155 1e293b 0f172a",   # 400/500 darkened: AA text contrast
    "red": "fef2f2 fee2e2 fecaca fca5a5 f87171 ef4444 dc2626 b91c1c 991b1b 7f1d1d",
    "amber": "fffbeb fef3c7 fde68a fcd34d fbbf24 f59e0b d97706 b45309 92400e 78350f",
    "emerald": "ecfdf5 d1fae5 a7f3d0 6ee7b7 34d399 10b981 059669 047857 065f46 064e3b",
    "sky": "f0f9ff e0f2fe bae6fd 7dd3fc 38bdf8 0ea5e9 0284c7 0369a1 075985 0c4a6e",
    "orange": "fff7ed ffedd5 fed7aa fdba74 fb923c f97316 ea580c c2410c 9a3412 7c2d12",
    "violet": "f5f3ff ede9fe ddd6fe c4b5fd a78bfa 8b5cf6 7c3aed 6d28d9 5b21b6 4c1d95",
    "brand": "effaf6 d5f2e8 aee4d2 7fcfb5 4fb597 2f9a7e 1f7a62 1f6655 1a5245 123c33",
}
# Dark slate is hand-tuned: low steps become dark surfaces, high steps become light ink.
DARK_SLATE = "161d26 1b232e 27313d 36414f 8592a3 a0abb9 b3bdca c9d1db dfe4eb f1f4f8"   # 400/500 >= 5:1 on dark surfaces
SURFACE = {"light": "ffffff", "dark": "121921"}
# Fill behind white text (buttons, chat bubbles). Separate from brand-600, which is a *text* colour in dark mode.
ACTION = {"light": "1f7a62", "dark": "1a7560"}
CANVAS = {"light": "f6f8fa", "dark": "0b1016"}


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a, b, t):  # t of a over b
    return tuple(round(x * t + y * (1 - t)) for x, y in zip(a, b, strict=True))


def dark_family(light_hexes):
    c = [rgb(h) for h in light_hexes.split()]
    bg = rgb(SURFACE["dark"])
    # tints become deep tinted surfaces, inks become light tints
    return [mix(c[8], bg, .32), mix(c[8], bg, .5), mix(c[7], bg, .6), c[6], c[4], c[5], c[4], c[2], c[1], c[0]]


def block(selector, values):
    lines = [f"{selector} {{"]
    for name, triplets in values.items():
        for step, t in zip(STEPS, triplets, strict=True):
            lines.append(f"  --{name}-{step}: {t[0]} {t[1]} {t[2]};")
    return lines


light = {k: [rgb(h) for h in v.split()] for k, v in LIGHT.items()}
dark = {k: dark_family(v) for k, v in LIGHT.items()}
dark["slate"] = [rgb(h) for h in DARK_SLATE.split()]
out = block(":root", light)
out += [f"  --surface: {' '.join(map(str, rgb(SURFACE['light'])))};", f"  --canvas: {' '.join(map(str, rgb(CANVAS['light'])))};", f"  --action: {' '.join(map(str, rgb(ACTION['light'])))};", "  color-scheme: light;", "}"]
out += block(":root.dark", dark)
out += [f"  --surface: {' '.join(map(str, rgb(SURFACE['dark'])))};", f"  --canvas: {' '.join(map(str, rgb(CANVAS['dark'])))};", f"  --action: {' '.join(map(str, rgb(ACTION['dark'])))};", "  color-scheme: dark;", "}"]
open(sys.argv[1], "w", encoding="utf-8").write("/* generated by gen_theme.py - Tailwind scales as CSS variables, redefined for dark mode */\n" + "\n".join(out) + "\n")
print("ok")
